import { PGlite } from '@electric-sql/pglite';
import test from 'node:test';
const alice = '11111111-1111-4111-8111-111111111111';
const bob = '22222222-2222-4222-8222-222222222222';
const guardPath = process.env.STEP_GUARD_SQL || new URL('../supabase/migrations/20261027134931_preserve_daily_step_totals.sql', import.meta.url);
const fixture = `
create role anon nologin; create role authenticated nologin; create schema auth;
create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$
 select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid;
$$;
grant usage on schema auth to anon, authenticated;
grant execute on function auth.uid() to anon, authenticated;
`;
const bigintSchema = `
create table public.step_goals(user_id uuid primary key references auth.users(id),
 daily_goal integer not null default 10000, timezone text not null default 'Asia/Kolkata',
 updated_at timestamptz not null default now());
create table public.daily_steps(id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id), step_date date not null,
 steps integer not null check(steps between 0 and 200000),
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
 unique(user_id,step_date));
alter table public.daily_steps enable row level security;
alter table public.step_goals enable row level security;
create policy existing_daily_owner on public.daily_steps to authenticated
 using ((select auth.uid())=user_id) with check ((select auth.uid())=user_id);
create policy existing_goal_owner on public.step_goals to authenticated
 using ((select auth.uid())=user_id) with check ((select auth.uid())=user_id);
grant usage on schema public to authenticated;
grant select,insert,update on public.daily_steps,public.step_goals to authenticated;
grant usage,select on sequence public.daily_steps_id_seq to authenticated;
`;
const upsert = `insert into public.daily_steps(user_id,step_date,steps) values($1,$2,$3)
 on conflict(user_id,step_date) do update set user_id=excluded.user_id,
 step_date=excluded.step_date,steps=excluded.steps returning *`;
const migrationDir = fileURLToPath(new URL('../supabase/migrations/', import.meta.url));

async function createDb(t, shape) {
  const db = await PGlite.create();
  t.after(() => db.close());
  await db.exec(fixture);
  await db.exec(await readFile(migrationDir + '20261026051059_create_water_tracking.sql', 'utf8'));
  await db.exec(shape === 'uuid'
    ? await readFile(migrationDir + '20261026162943_harden_step_tracking.sql', 'utf8')
    : bigintSchema);
  await db.query('insert into auth.users values($1),($2)', [alice,bob]);
  await db.query("insert into public.step_goals(user_id,daily_goal,timezone) values($1,7500,'UTC')", [alice]);
  await db.query('insert into public.water_entries(user_id,amount_ml) values($1,250)', [alice]);
  const { rows: [dates] } = await db.query(`select
    to_char((current_timestamp at time zone 'UTC')::date-2,'YYYY-MM-DD') as day,
    to_char((current_timestamp at time zone 'UTC')::date-3,'YYYY-MM-DD') as previous`);
  await db.query('insert into public.daily_steps(user_id,step_date,steps) values($1,$2,100),($3,$2,77)', [alice,dates.day,bob]);
  return { db, dates };
}
async function snapshot(db) {
  const columns = (await db.query(`select c.relname,a.attname,
    pg_catalog.format_type(a.atttypid,a.atttypmod) as type,a.attnotnull,a.attidentity,
    pg_catalog.pg_get_expr(d.adbin,d.adrelid) as default_value
    from pg_catalog.pg_class c join pg_catalog.pg_namespace n on n.oid=c.relnamespace
    join pg_catalog.pg_attribute a on a.attrelid=c.oid and a.attnum>0 and not a.attisdropped
    left join pg_catalog.pg_attrdef d on d.adrelid=c.oid and d.adnum=a.attnum
    where n.nspname='public' and c.relkind='r' order by c.relname,a.attnum`)).rows;
  const policies = (await db.query("select * from pg_policies where schemaname='public' order by tablename,policyname")).rows;
  const grants = (await db.query("select * from information_schema.table_privileges where table_schema='public' order by table_name,grantee,privilege_type")).rows;
  const columnGrants = (await db.query("select * from information_schema.column_privileges where table_schema='public' order by table_name,column_name,grantee,privilege_type")).rows;
  const security = (await db.query("select relname,relrowsecurity,relforcerowsecurity,relacl from pg_class where oid in ('public.daily_steps'::regclass,'public.step_goals'::regclass,'public.water_entries'::regclass,'public.water_goals'::regclass) order by relname")).rows;
  const goals = (await db.query('select * from public.step_goals order by user_id')).rows;
  const water = (await db.query('select * from public.water_entries order by id')).rows;
  return { columns,policies,grants,columnGrants,security,goals,water };
}
async function asUser(db, id, action) {
  await db.exec('set role authenticated');
  await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]);
  try { return await action(); } finally { await db.exec('reset role'); }
}
const rejectsCode = (db, sql, params, code) => assert.rejects(
  () => db.query(sql, params), (error) => error.code === code);

for (const shape of ['bigint','uuid']) {
  test(`${shape}: additive aggregate guard`, async (t) => {
    const { db,dates } = await createDb(t,shape);
    const guard = await readFile(guardPath,'utf8');
    const before = await snapshot(db);
    const rowsBefore = (await db.query('select * from public.daily_steps order by user_id,step_date')).rows;
    await t.test('preserves existing rows, ID defaults, policies, grants, goals and Water', async () => {
      await db.exec(guard);
      assert.deepEqual(await snapshot(db),before);
      assert.deepEqual((await db.query('select * from public.daily_steps order by user_id,step_date')).rows,rowsBefore);
    });
    await t.test('100 -> 500 -> 300/replay keeps one aggregate and stable stale timestamp', async () => {
      await asUser(db,alice,async () => {
        const first = (await db.query(upsert,[alice,dates.day,100])).rows[0];
        const higher = (await db.query(upsert,[alice,dates.day,500])).rows[0];
        const stale = (await db.query(upsert,[alice,dates.day,300])).rows[0];
        const replay = (await db.query(upsert,[alice,dates.day,500])).rows[0];
        assert.equal(higher.steps,500);
        assert.equal(stale.steps,500);
        assert.equal(replay.steps,500);
        assert.equal(String(first.id),String(higher.id));
        assert.equal(String(stale.id),String(higher.id));
        assert.equal(+stale.updated_at,+higher.updated_at);
        assert.equal(+replay.updated_at,+higher.updated_at);
        assert.equal(+higher.created_at,+first.created_at);
        assert.ok(+higher.updated_at>=+first.updated_at);
        assert.equal((await db.query('select count(*)::int n from public.daily_steps')).rows[0].n,1);
      });
    });
    await t.test('first-time zero sync and failed request followed by retry are idempotent', async () => {
      await asUser(db,alice,async () => {
        await rejectsCode(db,upsert,[alice,dates.previous,-1],'23514');
        const zero = (await db.query(upsert,[alice,dates.previous,0])).rows[0];
        const saved = (await db.query(upsert,[alice,dates.previous,40])).rows[0];
        const retry = (await db.query(upsert,[alice,dates.previous,40])).rows[0];
        assert.equal(saved.steps,40);
        assert.equal(String(zero.id),String(saved.id));
        assert.equal(String(saved.id),String(retry.id));
        assert.equal(+retry.updated_at,+saved.updated_at);
        assert.equal((await db.query('select count(*)::int n from public.daily_steps')).rows[0].n,2);
      });
    });
    await t.test('invalid, negative, oversized, null, impossible and future values are rejected', async () => {
      await asUser(db,alice,async () => {
        for (const count of [-1,200001,null]) await rejectsCode(db,upsert,[alice,dates.day,count],'23514');
        await rejectsCode(db,upsert,[alice,dates.day,'abc'],'22P02');
        await rejectsCode(db,upsert,[alice,dates.day,2.5],'22P02');
        await rejectsCode(db,upsert,[alice,'2026-02-30',3],'22008');
        for (const date of [null,'infinity','-infinity','0001-01-01 BC','9999-01-01','9998-12-31']) {
          await rejectsCode(db,upsert,[alice,date,3],'23514');
        }
      });
    });
    await t.test('direct updates preserve the maximum and cannot forge timestamps or identity', async () => {
      // Owner/admin exercises the trigger even where local UUID column grants reject first.
      const original = (await db.query('select * from public.daily_steps where user_id=$1 and step_date=$2',[alice,dates.day])).rows[0];
      for (const [clause,params] of [
        ['user_id=$3',[alice,dates.day,bob]],
        ['step_date=$3',[alice,dates.day,dates.previous]],
        [shape==='uuid'?'id=gen_random_uuid()':'id=id+100000',[alice,dates.day]],
        ["created_at='2020-01-01T00:00:00Z'",[alice,dates.day]],
      ]) await rejectsCode(db,`update public.daily_steps set ${clause} where user_id=$1 and step_date=$2`,params,'23514');
      const stale = (await db.query("update public.daily_steps set steps=1,updated_at='2150-01-01T00:00:00Z' where user_id=$1 and step_date=$2 returning *",[alice,dates.day])).rows[0];
      assert.equal(stale.steps,500);
      assert.equal(+stale.updated_at,+original.updated_at);
      const higher = (await db.query("update public.daily_steps set steps=501,updated_at='2150-01-01T00:00:00Z' where user_id=$1 and step_date=$2 returning *",[alice,dates.day])).rows[0];
      assert.equal(higher.steps,501);
      assert.notEqual(higher.updated_at.toISOString(),'2150-01-01T00:00:00.000Z');
      assert.equal(+higher.created_at,+original.created_at);
    });
    await t.test('RLS still isolates users and missing subjects', async () => {
      await asUser(db,bob,async () => {
        assert.equal((await db.query('select steps from public.daily_steps')).rows[0].steps,77);
        assert.equal((await db.query('update public.daily_steps set steps=600 where user_id=$1 returning *',[alice])).rows.length,0);
        await rejectsCode(db,upsert,[alice,dates.day,600],'42501');
      });
      await asUser(db,'',async () => assert.equal((await db.query('select * from public.daily_steps')).rows.length,0));
    });
    await t.test('repeat application is safe and uses one enabled invoker guard', async () => {
      const current = (await db.query('select * from public.daily_steps order by user_id,step_date')).rows;
      await db.exec(guard);
      assert.deepEqual(await snapshot(db),before);
      assert.deepEqual((await db.query('select * from public.daily_steps order by user_id,step_date')).rows,current);
      const triggers = (await db.query("select t.tgenabled,p.prosecdef,p.proconfig from pg_trigger t join pg_proc p on p.oid=t.tgfoid where t.tgrelid='public.daily_steps'::regclass and t.tgname='zz_steps_v1_guard_daily'")).rows;
      assert.equal(triggers.length,1);
      assert.equal(triggers[0].tgenabled,'O');
      assert.equal(triggers[0].prosecdef,false);
      assert.ok(triggers[0].proconfig.some((value)=>value.startsWith('search_path=')));
    });
  });
}

for (const problem of ['missing-column','partial-unique','trigger-collision']) {
  test(`preflight: ${problem} aborts without replacing data or policies`, async (t) => {
    const { db } = await createDb(t,'bigint');
    let expected;
    if (problem==='missing-column') {
      await db.exec('alter table public.daily_steps rename column created_at to original_created_at');
      expected=/daily_steps.created_at/;
    } else if (problem==='partial-unique') {
      await db.exec(`alter table public.daily_steps drop constraint daily_steps_user_id_step_date_key;
        create unique index partial_daily_unique on public.daily_steps(user_id,step_date) where steps>=0`);
      expected=/usable unique index/;
    } else {
      await db.exec(`create function public.unrelated_guard() returns trigger language plpgsql as $$ begin return new; end $$;
        create trigger zz_steps_v1_guard_daily before insert or update on public.daily_steps for each row execute function public.unrelated_guard()`);
      expected=/Unexpected existing trigger/;
    }
    const before = await snapshot(db);
    const rows = (await db.query('select * from public.daily_steps order by user_id,step_date')).rows;
    await assert.rejects(()=>readFile(guardPath,'utf8').then((sql)=>db.exec(sql)),expected);
    await db.exec('rollback');
    assert.deepEqual(await snapshot(db),before);
    assert.deepEqual((await db.query('select * from public.daily_steps order by user_id,step_date')).rows,rows);
    assert.equal((await db.query("select to_regprocedure('public.steps_v1_guard_daily()') as fn")).rows[0].fn,null);
  });
}
